package com.xiaoming.day31.common.exception;

import com.xiaoming.day31.common.ResultCode;

/**
 * "业务规则冲突" 异常 → HTTP 409
 *
 * ⭐ 400 / 404 / 409 三个有什么区别？这是今天最容易混的地方，记住这张表：
 *
 *   ┌────────┬──────────────────────────┬─────────────────────────────┐
 *   │ 状态码 │ 什么错                    │ 例子                         │
 *   ├────────┼──────────────────────────┼─────────────────────────────┤
 *   │ 400    │ **请求本身就不合法**       │ price=-5、id 写了 abc        │
 *   │        │ （改请求就能通过）         │ （前端该拦在输入框）          │
 *   ├────────┼──────────────────────────┼─────────────────────────────┤
 *   │ 404    │ **东西不存在**             │ 查 id=999 的 SKU             │
 *   │        │ （地址/ID 错了）           │ （改 ID 就能通过）            │
 *   ├────────┼──────────────────────────┼─────────────────────────────┤
 *   │ 409    │ **请求合法，但违反业务规则**│ 库存只有 10，你想出库 100     │
 *   │        │ （得先改变现实才能通过）    │ （先去进货，再重试）          │
 *   └────────┴──────────────────────────┴─────────────────────────────┘
 *
 * 记忆口诀：**400 是"你说的不对"，404 是"你要的没有"，409 是"现在不行"**。
 */
public class BizRuleException extends BaseException {

    public BizRuleException(String message) {
        super(ResultCode.BIZ_CONFLICT.getHttp(), message);   // 409
    }
}