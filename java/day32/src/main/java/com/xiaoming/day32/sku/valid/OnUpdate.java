package com.xiaoming.day32.sku.valid;

/**
 * ⭐ 校验分组 —— "更新"场景（PUT /sku 用这一组）
 *
 * 和 {@link OnCreate} 是一对：都是**空接口**，只为给注解当"组名"用。
 *
 * 【更新场景的规则和新增正好互补】
 *   ┌────────┬──────────────────────┬──────────────────────┐
 *   │ 字段    │ 新增（OnCreate）      │ 更新（OnUpdate）      │
 *   ├────────┼──────────────────────┼──────────────────────┤
 *   │ id     │ @Null（不许自己传）    │ @NotNull（必须传）    │
 *   │ title  │ @NotBlank（必填）      │ @Size(min=1)（可不传，传了不能是空）│
 *   │ code   │ @SkuCode（必给）       │ 不校验（编码不允许改） │
 *   │ price  │ @NotNull + @Min(0)    │ @Min(0)（可以不传）   │
 *   │ stock  │ @NotNull + @Min(0)    │ @Min(0)（可以不传）   │
 *   └────────┴──────────────────────┴──────────────────────┘
 *
 * ⭐ 一头一尾两个"最典型"的例子正好说明了分组的意义：
 *    · `id`：**同一个字段、两条相反规则**（新增必须空、更新必须有）
 *    · `code`：**只在某一组存在**（新增要校验、更新完全不看）
 *   一套注解 + 两个组，把这两件事都表达了 —— 不用写两个 DTO 类。
 *
 * ⚠️ 别忘了那个坑：`groups` 只写在一个组上 = 这个约束**只在那一组生效**。
 *    哪一组都没写 = 只属于默认组 Default，而**指定了组之后 Default 就不再参与**了。
 */
