--  Day 35 · schema-h2.sql —— **同一份表结构的 H2 版**（对照用）
-- ═══════════════════════════════════════════════════════════════════════════════
--
--  【为什么要给一份 H2 版？—— 因为它能回答"H2 → MySQL 到底差在哪"】
--    schema.sql（MySQL 版）和本文件（H2 版）是**同一份业务表结构**，
--    但两者**一行都不能互换执行**。逐条对比就是今天第 3 步的学习材料：
--
--  ┌──────────────┬────────────────────────────────────┬────────────────────────────────────┐
--  │ 差异点        │ H2（本文件 / 交付版用的）             │ MySQL（schema.sql）                 │
--  ├──────────────┼────────────────────────────────────┼────────────────────────────────────┤
--  │ ① 自增        │ BIGINT GENERATED BY DEFAULT AS IDENTITY │ BIGINT NOT NULL AUTO_INCREMENT   │
--  │              │ （SQL 标准写法）                      │ （MySQL 专有；标准里没这个词）        │
--  │ ② 建索引      │ CREATE UNIQUE INDEX 名字 ON 表 (列)   │ 一样能用；但 MySQL 还多一个"写在      │
--  │              │ （标准写法，两边都能跑）               │ CREATE TABLE 里的 UNIQUE KEY 名 (列)"│
--  │              │                                      │ 这种内联写法 —— **H2 不认**          │
--  │ ③ 引擎/字符集 │ ❌ 没有这个概念                        │ ENGINE=InnoDB DEFAULT CHARSET=utf8mb4│
--  │              │   H2 是纯 Java 的，没有存储引擎        │ COLLATE=utf8mb4_0900_ai_ci          │
--  │ ④ 列注释      │ ❌ 不支持 `COMMENT '...'`（建表会报语法错）│ ✅ 每个列/表都能带 COMMENT（很有用）  │
--  │ ⑤ 列级字符集  │ ❌ 不支持 `CHARACTER SET utf8`         │ ✅ 支持（ch_demo 表就靠它做对照）     │
--  │ ⑥ 重置自增    │ TRUNCATE ... RESTART IDENTITY         │ TRUNCATE TABLE ...（自带重置）       │
--  │ ⑦ 表名大小写  │ 一律转成大写（元数据里是 SKU）          │ Windows 上不敏感、**Linux 上敏感**！  │
--  │ ⑧ emoji      │ CHARACTER SET 概念没有 → 存得进去      │ utf8mb4 才存得进去（utf8 报 1366）   │
--  │ ⑨ 长度校验    │ ⚠️ VARCHAR(20) 塞 21 个字符**不报错**   │ 报 ERROR 1406 Data too long          │
--  └──────────────┴────────────────────────────────────┴────────────────────────────────────┘
--
--  ⭐⭐ 其中 ⑦⑧⑨ 三条是**真机实测**出来的（H2 2.2.224 / MySQL 8.4.5），
--     不是抄的文档结论 —— 尤其第 ⑨ 条：**H2 居然不校验 VARCHAR 长度**，
--     所以"超长字符串"这个刁钻用例**只能在 MySQL 上看到效果**（本包已诚实标注）。
--
--  【本文件和交付版代码的关系】
--    交付版的建表语句现在**还在** `db/DataInitializer.java` 里（Java 字符串），
--    内容和本文件**逐字对应**。本文件是给你"对照阅读"用的，
--    TODO③ 之后 DataInitializer 里的 DDL 会被删掉、改用 schema.sql（MySQL 版）。
--    📌 换句话说：**交付版永远不需要执行本文件**，它是"地图"不是"路"。
--
--  ⚠️ 本文件只能对 **H2 库**（jdbc:h2:mem:day35）执行；
--     拿它去连 MySQL 会在第一句 DROP 之后就失败（自增那句）。
