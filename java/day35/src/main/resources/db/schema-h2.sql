DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS audit_log;
DROP TABLE IF EXISTS sku;

-- ① 商品表（H2 版：把 MySQL 的 AUTO_INCREMENT / ENGINE / COMMENT 全去掉）
CREATE TABLE sku (
  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 自增主键（H2 写法）
  code       VARCHAR(20)  NOT NULL,                                      -- 唯一约束在下面单独建
  title      VARCHAR(100) NOT NULL,
  price      DECIMAL(10,2) NOT NULL DEFAULT 0.00,                        -- 金额：两边都支持 DECIMAL
  stock      INT          NOT NULL DEFAULT 0,
  is_deleted TINYINT      NOT NULL DEFAULT 0,                            -- 逻辑删除
  created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_sku_code UNIQUE (code),                                  -- 唯一约束（H2 只认标准写法）
  CONSTRAINT ck_sku_price CHECK (price >= 0),
  CONSTRAINT ck_sku_stock CHECK (stock >= 0 AND stock <= 500)
);

-- ⭐ 联合唯一索引：H2 和 MySQL 都吃这句标准写法（所以交付版和答案版都能建）
CREATE UNIQUE INDEX uk_sku_code_alive ON sku (code, is_deleted);

-- ② 订单表（H2 版）
CREATE TABLE orders (
  id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku_id     BIGINT        NOT NULL,
  sku_code   VARCHAR(20)   NOT NULL,
  title      VARCHAR(100)  NOT NULL,
  `count`    INT           NOT NULL,             -- 与 COUNT() 同名，加反引号（H2 也吃，实测）
  amount     DECIMAL(10,2) NOT NULL,
  created_at TIMESTAMP     NOT NULL,
  CONSTRAINT ck_orders_count  CHECK (`count` > 0),
  CONSTRAINT ck_orders_amount CHECK (amount >= 0),
  CONSTRAINT fk_orders_sku FOREIGN KEY (sku_id) REFERENCES sku (id)   -- 外键：两边语法一样
);

-- ③ 审计表（H2 版）
CREATE TABLE audit_log (
  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action     VARCHAR(50)  NOT NULL,
  detail     VARCHAR(200) NOT NULL,
  created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_audit_action_detail ON audit_log (action, detail);

