package com.xiaoming.day35.db;

import jakarta.annotation.PostConstruct;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.sql.init.dependency.DependsOnDatabaseInitialization;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import java.time.LocalDate;
import java.util.List;
import java.util.Map;

/**
 * ⭐⭐ 自检表结构 + 插种子数据（本项目的"数据库初始化器"）—— **Day35 的主角之一**
 *    （TODO③ 之后：建表已搬去 schema.sql，本类不再持有任何 DDL）
 *
 * 【本类索引：1 个入口 + 1 个复位 + 2 个插数据方法】
 *   ┌──────────────────────┬────────────────────────────────────────────────────────────┐
 *   │ init()               │ @PostConstruct —— 启动时跑一次：自检表结构 → 插种子            │
 *   │ reset()              │ ⭐ 清空 + 重新插种子（POST /db/reset 调用，做实验前一键复位）  │
 *   │ ── 建表 ──            │ ⭐ 已搬去 src/main/resources/db/schema.sql（TODO③）            │
 *   │ ── 插数据 ──          │                                                            │
 *   │ seedSku()            │ 3 条种子商品（和 Day31~34 **完全一样**，方便对比老功能没退化）│
 *   │ seedAuditLog()       │ 1 条"日终对账"审计（给联合唯一索引当靶子）                  │
 *   └──────────────────────┴────────────────────────────────────────────────────────────┘
 *
 * 【⭐⭐ Day35 的四张表和 Day34 的三张表差在哪？—— 就差"约束"和"类型"】
 *   Day34（H2 内存库，随手建的）           Day35（按真实项目标准建的）
 *   ────────────────────────────────────  ──────────────────────────────────────────────
 *   code VARCHAR(20) NOT NULL 而已         code 上多一条 UNIQUE（唯一约束）
 *   price INT                              price DECIMAL(10,2)（金额不能是 float/double）
 *   没有 is_deleted 这一列                 sku.is_deleted TINYINT NOT NULL DEFAULT 0（逻辑删除）
 *   没有外键                               orders.sku_id 外键指向 sku.id
 *   没有 CHECK                             stock / count / amount 上都有 CHECK
 *   表之间没有任何"唯一"约束               audit_log 有联合唯一索引 (action, detail)
 *   没有字符集概念                         ch_demo 把 utf8 和 utf8mb4 摆在一起对比
 *
 *   ⭐ 这些约束**不是装饰**：它们会在"应用层没想到"的时候兜住错误数据（Day32 记下的那笔债）。
 *      今天你要亲眼看到"数据库拒绝了这次插入"长什么样 → 见题目第 6 步。
 *
 * 【⭐ 为什么今天仍然不用 schema.sql / data.sql？—— Day35 这里有个"转折"】
 *   Day30~34 我们一直是"在 Java 里手写 DDL"（能打日志、能被 /db/reset 复用）。
 *   但今天要到真 MySQL 上去，**手写 DDL 会立刻撞墙**：
 *     · H2 的自增写法 `BIGINT GENERATED BY DEFAULT AS IDENTITY` —— MySQL 不认
 *     · MySQL 的 `ENGINE=InnoDB DEFAULT CHARSET=utf8mb4` / `COMMENT '...'`
 *       / 列级 `CHARACTER SET utf8` —— H2 不认
 *     · MySQL 的建表语句能带 `UNIQUE KEY 名字 (...)` —— H2 只认标准 `UNIQUE (...)`
 *   → 所以真实项目里，**建表语句是"数据库的资产"，要单独放一个 .sql 文件**（本包给了
 *     `schema.sql` 的 MySQL 版和 `schema-h2.sql` 的 H2 版，两个都真机跑过）。
 *     📌 TODO③ 就是让你亲手把"Java 里的 DDL"换成"SQL 文件 + 一个开关"。
 *
 * 【⭐⭐ 为什么必须有 /db/reset？—— Day34 传下来的实验纪律】
 *   事务实验是"改变数据 + 看数据有没有变回去"，所以**每次实验前必须回到同一个起点**。
 *   不然你第二次跑的时候，"订单表有 1 行"到底是因为上次没回滚、还是因为这次插进去了，
 *   根本分不清。→ 规矩：**复位 → 只做一个操作 → 立刻查库**。
 */
@Component
@DependsOnDatabaseInitialization   // ⭐ 保证 schema.sql 先跑完，再执行本类的 @PostConstruct
public class DataInitializer {

    private static final Logger log = LoggerFactory.getLogger(DataInitializer.class);

    private final JdbcTemplate jdbc;

    /** 构造器注入（Day33 学的姿势：final + 构造器，忘了传编译期就红） */
    public DataInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    /** 应用启动时跑一次 */
    @PostConstruct
    public void init() {
        // ⭐ TODO③ 之后："谁来建表"的答案变了 —— 从"Java 里手写 DDL"变成"schema.sql + 一个开关"
        //    （spring.sql.init.mode=always，见 application.properties ⑤）
        //    所以这里**不再 DROP、不再建表**，只做两件事：
        //      ① 自检：schema.sql 到底把表建出来没有？连的是哪个库、什么版本？
        //      ② 插种子数据（/db/reset 也复用下面两个 seed 方法）
        //    📌 这就是 DDL 和 DML 的分工：结构归 .sql 文件，数据归 Java。
        Map<String, Object> info = jdbc.queryForMap("SELECT DATABASE() AS db, VERSION() AS ver");

        Integer tables = jdbc.queryForObject("""
                SELECT COUNT(*) FROM information_schema.tables
                 WHERE table_schema = DATABASE()
                   AND table_name IN ('sku', 'orders', 'audit_log', 'ch_demo')
                """, Integer.class);
        if (tables == null || tables != 4) {
            throw new IllegalStateException("[db] 表结构自检失败：期望 4 张表，实际 " + tables
                    + " 张 —— schema.sql 没执行成功？检查 spring.sql.init.mode / continue-on-error");
        }
        log.info("[db] 已连接 {}（MySQL {}）；表结构自检通过：sku / orders / audit_log / ch_demo 都在（由 schema.sql 建好）",
                info.get("db"), info.get("ver"));

        seedSku();
        seedAuditLog();
    }

    /**
     * ⭐ 一键复位：清空所有数据 + 重新插种子（POST /db/reset 调用它）
     *
     * ⚠️⚠️ 这里存着一条**Day34 真机踩出来的坑**，别改错：
     *   当时写的是 `DELETE FROM sku`（"清空不就是删掉所有行吗"）—— 结果**整个项目跑不通了**：
     *   复位之后 SKU 的自增 id 变成了 **4、5、6**（DELETE 只删行，**不会让自增计数器归零**），
     *   于是所有写死 `skuId=1` 的接口全都返回 **404 SKU 不存在：id=1**。
     *
     *   `TRUNCATE TABLE ... RESTART IDENTITY` 才是对的：清空 + **把自增重新从 1 开始**。
     *
     *   ⭐ 教训：**"清空数据"和"重置状态"是两件事**。凡是"做实验前要回到同一个起点"的地方，
     *      都要问一句"自增、序列、时间戳这些**隐藏状态**也回去了吗？"
     *
     *   ⭐⭐ Day35 的新知识点（这句话在 MySQL 上会变）：
     *      `RESTART IDENTITY` 是 **H2 的方言**。MySQL 的 `TRUNCATE TABLE` **自带重置自增**
     *      （MySQL 里也**没有** `RESTART IDENTITY` 这个写法，写了直接报语法错）。
     *      → 所以换 MySQL 时，这三行要改成 `TRUNCATE TABLE xxx`（见 schema.sql 文件头注释）。
     *
     *   ⚠️ 另外注意：SQL 里 `orders` 有外键指向 `sku`，所以**必须先清 orders 再清 sku**。
     *      （顺序反了在 MySQL 上会报 `Cannot truncate a table referenced in a foreign key
     *       constraint`。）
     *
     *   ⚠️⚠️ Day35 真机实测发现的**第二个坑**（比想象中严重，写下来免得你再踩）：
     *      H2 上光调换顺序**还不够** —— 只要有**任何**外键指向 sku，
     *      `TRUNCATE TABLE sku ...` 就会失败（就算 orders 已经清空了）：
     *        org.h2.jdbc.JdbcSQLSyntaxErrorException: Cannot truncate "PUBLIC.SKU";
     *        SQL statement: TRUNCATE TABLE sku RESTART IDENTITY [90106-224]
     *      → 整个 /db/reset 返回 **500**（而且前两句 TRUNCATE 已经执行了：
     *        orders 和 audit_log 被清空，sku 没清 → **库里处于半复位状态**）。
     *      ⭐ 解法（本方法在做的）：**先关掉外键检查，干完活再打开** ——
     *         `SET REFERENTIAL_INTEGRITY FALSE` … `SET REFERENTIAL_INTEGRITY TRUE`
     *         这是 **H2 的方言**；MySQL 里对应的是
     *         `SET FOREIGN_KEY_CHECKS = 0` … `SET FOREIGN_KEY_CHECKS = 1`。
     *      📌 教训：**"关外键检查"这类语句是两个数据库方言差异最大的地方之一**，
     *         换库的时候一定要专门测一遍"复位"这个动作（今天你就测了）。
     */
    public void reset() {
        // 关掉外键检查：MySQL 里只要有外键指向 sku，TRUNCATE sku 就会被拒绝
        // （对应 H2 的 SET REFERENTIAL_INTEGRITY；这是两个数据库方言差异最大的地方之一）
        jdbc.execute("SET FOREIGN_KEY_CHECKS = 0");
        try {
            // MySQL 的 TRUNCATE **自带重置自增**，所以不需要（也没有）RESTART IDENTITY
            jdbc.execute("TRUNCATE TABLE orders");
            jdbc.execute("TRUNCATE TABLE audit_log");
            jdbc.execute("TRUNCATE TABLE sku");
            try {
                jdbc.execute("TRUNCATE TABLE ch_demo");
            } catch (Exception e) {
                log.debug("[db] ch_demo 不存在，跳过");
            }
        } finally {
            // ⭐ 必须放 finally：万一上面某句炸了，外键检查也得给我开回来
            jdbc.execute("SET FOREIGN_KEY_CHECKS = 1");
        }
        seedSku();
        seedAuditLog();
        log.info("[db] 已复位：orders=0, audit_log=1, sku=3（TRUNCATE 顺带把自增 id 也归 1 了）");
    }

    /**
     * 插种子数据 —— 和 Day31~34 **完全一样的三条**（故意不变，方便你对比"老功能没退化"）
     *
     * ⭐ 注意三条数据的**库存**：10 / 3 / 0 —— 这是精心设计的，能覆盖三种场景：
     *    1 号（10 件）→ 怎么下单都够
     *    2 号（3 件） → 下单 5 件就"库存不足"（409）
     *    3 号（0 件） → 可以直接删（没有库存 → 删除接口放行）
     */
    private void seedSku() {
        jdbc.update("INSERT INTO sku (code, title, price, stock) VALUES (?, ?, ?, ?)",
                "SKU-0001", "深入理解 Java 虚拟机", 108.00, 10);
        jdbc.update("INSERT INTO sku (code, title, price, stock) VALUES (?, ?, ?, ?)",
                "SKU-0002", "Java 并发编程实战", 79.00, 3);
        jdbc.update("INSERT INTO sku (code, title, price, stock) VALUES (?, ?, ?, ?)",
                "SKU-0003", "SpringBoot 实战", 89.00, 0);

        List<Map<String, Object>> rows = jdbc.queryForList(
                "SELECT id, code, title, price, stock, is_deleted FROM sku ORDER BY id");
        for (Map<String, Object> r : rows) {
            // ⚠️ 换 MySQL 后列标签是小写（H2 会大写成 ID/CODE…），所以这里必须用 "id" 而不是 "ID"
            log.info("[db] 种子 SKU：id={} code={} title={} price={} stock={} is_deleted={}",
                    r.get("id"), r.get("code"), r.get("title"), r.get("price"), r.get("stock"), r.get("is_deleted"));
        }
    }

    /**
     * 插 1 条审计种子 —— **专门给"联合唯一索引"当靶子**
     *
     * 【为什么这条必须有？】
     *   第 6 步的债点实验要看到"数据库拒绝了一条重复插入"。最自然的复现方式就是：
     *     ① 数据库里已经有 `('DAILY_CLOSE', '日终对账完成 <今天>')` 这一条（本方法插的）
     *     ② 你再往 /db/sql 打**一模一样**的一条 → 数据库立刻拒绝
     *   如果 audit_log 是空的，"重复"就无从谈起（你得先插两条才能撞上）。
     *
     * ⭐ 顺便注意 detail 里带了日期：`日终对账完成 2026-10-23`。
     *   这正是"联合唯一索引"的现实用法 —— 每天的日终对账只记一次，
     *   第二天日期变了，(action, detail) 就不同了，**不会**被拦。
     */
    private void seedAuditLog() {
        String day = LocalDate.now().toString();
        jdbc.update("INSERT INTO audit_log (action, detail) VALUES (?, ?)",
                "DAILY_CLOSE", "日终对账完成 " + day);
        log.info("[db] 种子审计：action=DAILY_CLOSE detail=日终对账完成 {}", day);
    }
}
