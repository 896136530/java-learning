package com.xiaoming.day34.db;

import jakarta.annotation.PostConstruct;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import java.util.List;
import java.util.Map;

/**
 * ⭐ 建表 + 插种子数据（本项目的"数据库初始化器"）
 *
 * 【本类索引：1 个入口 + 3 张表 + 1 个复位方法】
 *   ┌──────────────────┬──────────────────────────────────────────────────────┐
 *   │ init()           │ @PostConstruct —— 应用启动时自动跑一次：建 3 张表 + 插种子  │
 *   │ reset()          │ ⭐ 清空 + 重新插种子（被 POST /db/reset 调用，做实验前一键复位）│
 *   │ ── 表 ──          │                                                      │
 *   │ sku              │ 商品表（id / code / title / price / stock）＝ Day33 那 3 条 │
 *   │ orders           │ ⭐ 今天新增：订单表（下单时往这里插一行）                  │
 *   │ audit_log        │ ⭐ 今天新增：审计表（演示 REQUIRES_NEW 传播行为要用）      │
 *   └──────────────────┴──────────────────────────────────────────────────────┘
 *
 * 【为什么不用 schema.sql / data.sql？】
 *   SpringBoot 支持把 SQL 写在 resources/schema.sql + data.sql 里自动执行，很省事。
 *   但今天我们**故意手写**，因为：
 *     ① 能打日志（启动窗口里看得见"建了三张表、插了三条数据"，出问题一眼定位）
 *     ② 能被 /db/reset 反复调用（做事务实验前必须复位，见下）
 *     ③ 注释能写在 SQL 旁边（哪列是干嘛的一目了然）
 *
 * 【⭐⭐ 为什么必须有 /db/reset？——这是今天最重要的一条实验纪律】
 *   事务实验是"改变数据 + 看数据有没有变回去"，所以**每次实验前必须回到同一个起点**。
 *   不然你第二次跑的时候，"订单表有 1 行"到底是因为上次没回滚、还是因为这次插进去了，
 *   根本分不清。→ 规矩：**复位 → 只做一个操作 → 立刻查库**。
 *
 * 【@PostConstruct 是什么？】
 *   `jakarta.annotation.PostConstruct`（Java 标准注解，不是 Spring 的）：
 *   标在方法上 = "这个 Bean 被创建、依赖注入完之后，**立刻执行这个方法一次**"。
 *   ⭐ 它比 ApplicationRunner 更早（发生在 Spring 容器启动过程中，Tomcat 还没开门），
 *   所以不用担心"第一个请求来了表还没建好"。
 */
@Component
public class DataInitializer {

    private static final Logger log = LoggerFactory.getLogger(DataInitializer.class);

    private final JdbcTemplate jdbc;

    /** 构造器注入（Day33 TODO③ 学的姿势：final + 构造器，忘了传编译期就红） */
    public DataInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    /** 应用启动时跑一次 */
    @PostConstruct
    public void init() {
        createTables();
        seed();
    }

    /**
     * ⭐ 一键复位：清空所有数据 + 重新插种子（POST /db/reset 调用它）
     *
     * ⚠️⚠️ 用 **DELETE** 还是 **TRUNCATE**？—— 这里有个**真机实测踩出来的坑**，别改错：
     *
     *   我第一版写的是 `DELETE FROM sku`（"清空不就是删掉所有行吗"）—— 结果**整个项目跑不通了**：
     *   复位之后 SKU 的自增 id 变成了 **4、5、6**（DELETE 只删行，**不会让自增计数器归零**），
     *   于是所有写死 `skuId=1` 的接口全都返回 **404 SKU 不存在：id=1**。
     *
     *   `TRUNCATE TABLE ... RESTART IDENTITY` 才是对的：清空 + **把自增重新从 1 开始**。
     *   这让"复位"变成真正的"回到出厂状态"（id 1/2/3、库存 10/3/0）。
     *
     *   ⭐ 教训：**"清空数据"和"重置状态"是两件事**。凡是"做实验前要回到同一个起点"的地方，
     *      都要问一句"自增、序列、时间戳这些**隐藏状态**也回去了吗？"
     *      （Day35 换 MySQL 时，对应写法是 `TRUNCATE TABLE sku` —— MySQL 的 TRUNCATE 自带重置自增。）
     */
    public void reset() {
        jdbc.execute("TRUNCATE TABLE orders RESTART IDENTITY");
        jdbc.execute("TRUNCATE TABLE audit_log RESTART IDENTITY");
        jdbc.execute("TRUNCATE TABLE sku RESTART IDENTITY");
        seed();
        log.info("[db] 已复位：orders=0, audit_log=0, sku=3（自增 id 也回到 1）");
    }

    // ═══════════════════════ 建表 ═══════════════════════

    /**
     * 建 3 张表。
     *
     * ⚠️ 语法小坑（Day35 换 MySQL 时会变）：
     *   `BIGINT GENERATED BY DEFAULT AS IDENTITY` 是 **H2 / SQL 标准**的自增写法；
     *   MySQL 里要写 `BIGINT AUTO_INCREMENT`。Day35 会亲手改这一处。
     *
     * ⚠️ `DROP TABLE IF EXISTS` 放在最前面：方便你反复启动（H2 内存库其实每次都是空的，
     *    但万一你改成了文件库 `jdbc:h2:file:...`，这句就能防止"表已存在"报错）。
     */
    private void createTables() {
        jdbc.execute("DROP TABLE IF EXISTS orders");
        jdbc.execute("DROP TABLE IF EXISTS audit_log");
        jdbc.execute("DROP TABLE IF EXISTS sku");

        jdbc.execute("""
                CREATE TABLE sku (
                    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    code   VARCHAR(20)  NOT NULL,
                    title  VARCHAR(100) NOT NULL,
                    price  INT          NOT NULL,
                    stock  INT          NOT NULL
                )
                """);

        // ⭐ 订单表：下单接口往这里插一行。amount = price * count（金额今天先用 INT，
        //    Day35 换 MySQL 时会讲"金额必须用 DECIMAL，不能用 float/double"）
        jdbc.execute("""
                CREATE TABLE orders (
                    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sku_id     BIGINT       NOT NULL,
                    sku_code   VARCHAR(20)  NOT NULL,
                    title      VARCHAR(100) NOT NULL,
                    count      INT          NOT NULL,
                    amount     INT          NOT NULL,
                    created_at TIMESTAMP    NOT NULL
                )
                """);

        // ⭐ 审计表：演示"传播行为 REQUIRES_NEW"用（主业务回滚了，审计日志要不要留？）
        jdbc.execute("""
                CREATE TABLE audit_log (
                    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    action     VARCHAR(50)  NOT NULL,
                    detail     VARCHAR(200) NOT NULL,
                    created_at TIMESTAMP    NOT NULL
                )
                """);

        log.info("[db] 建表完成：sku / orders / audit_log");
    }

    /**
     * 插种子数据 —— 和 Day31/32/33 **完全一样的三条**（故意不变，方便你对比"老功能没退化"）
     */
    private void seed() {
        jdbc.update("INSERT INTO sku (code, title, price, stock) VALUES (?, ?, ?, ?)",
                "SKU-0001", "深入理解 Java 虚拟机", 108, 10);
        jdbc.update("INSERT INTO sku (code, title, price, stock) VALUES (?, ?, ?, ?)",
                "SKU-0002", "Java 并发编程实战", 79, 3);
        jdbc.update("INSERT INTO sku (code, title, price, stock) VALUES (?, ?, ?, ?)",
                "SKU-0003", "SpringBoot 实战", 89, 0);

        List<Map<String, Object>> rows = jdbc.queryForList("SELECT id, code, title, price, stock FROM sku ORDER BY id");
        for (Map<String, Object> r : rows) {
            log.info("[db] 种子 SKU：id={} code={} title={} price={} stock={}",
                    r.get("ID"), r.get("CODE"), r.get("TITLE"), r.get("PRICE"), r.get("STOCK"));
        }
    }
}