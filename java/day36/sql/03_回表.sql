-- ① 走主键（聚簇索引）：叶子节点就是整行，顺序读完即可，不回表
SELECT SUM(age) FROM member WHERE id BETWEEN 1 AND 20000;

-- ② 走二级索引 idx_phone：叶子只有 id，每行都要拿 id 回主键树再取 age（回表 2 万次）
SELECT SUM(age) FROM member WHERE phone BETWEEN '13800000001' AND '13800020000';
