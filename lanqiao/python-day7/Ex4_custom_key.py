# 题 4：自定义 key（按长度 + 字典序）
# 输入：一行，若干个用空格隔开的英文单词（都是小写字母）
# 输出：一行，按「长度从小到大；长度相同的按字典序从小到大」排好，用空格隔开
# 提示：key=lambda w: (len(w), w) —— 同样是一个元组 key，先比长度，再比单词本身
# 自测：故意造两个长度相同的词（如 ant / cat），再看只有 1 个词的情况

# ===== 你的代码写在这里 =====
row=input().split()
row.sort(key=lambda w:(len(w),w))
print(' '.join(row))
