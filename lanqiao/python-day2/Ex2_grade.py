# 题 2：成绩等级
# 输入：一个整数 score（0~100）
# 输出：一行—— ≥90 优秀 / ≥80 良好 / ≥60 及格 / 其余 不及格
# 提示：if / elif / else 从上往下，第一个满足就命中

# ===== 你的代码写在这里 =====
score=int(input("请输入成绩："))
if(score>=90):
    print("优秀")
elif(score>=80):
    print("良好")
elif(score>=60):
    print("及格")
else:
    print("不及格")
