# 题 5：n 个数里找最大（蓝桥姿势）
# 输入：
#   第一行：整数 n（有几个数）
#   接下来 n 行：每行一个整数
# 输出：一行，其中最大的数
# 提示：打擂法——初始擂主取第一个数，谁更大谁上位

# ===== 你的代码写在这里 =====
n=int(input("请输入一个整数:"))
print("请输入几个整数：")
max=int(input())
for i in range(1,n):
    temp=int(input())
    if(temp>max):
        max=temp
print(f"最大的数:{max}")
