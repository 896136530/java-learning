# 输入：一行两个整数 n k（1 <= k <= n <= 200）
# 输出：一行，把 n 划分成 k 个正整数之和的方案数（不计顺序，1+1+5 和 5+1+1 算同一种）
# 要求：递归 + 记忆化；答案可能很大（Python 整数不会溢出，放心打）
# 提示：两种思路选一个
#   ① 枚举式：规定后一个数 >= 前一个数（不降序），dfs(剩余, 还要分几份, 最小能取几)
#   ② 递推式：f(n, k) = f(n-1, k-1) + f(n-k, k)
#       第一种方案里一定有个 1 → 拿掉一个 1，变成"n-1 分 k-1 份"
#       第二种方案里每份都 >= 2 → 每份先减 1，变成"n-k 分 k 份"
#       出口：k == 1 或 k == n → 1 种；k > n → 0 种
#   ⚠️ 不加记忆化，n=200 时会慢到跑不完
