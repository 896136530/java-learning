# 题 5：借教室（差分 + 顺序判定）⭐
# 输入：第一行 n；第二行 n 个整数（每天上限 r[i]）；第三行 k；接下来 k 行每行 L R v
# 输出：全部能满足 → 一行 0
#       否则 → 两行：第一行是**第一个无法满足的申请编号**（从 1 开始）
#                     第二行是那天**编号最小**的超量位置（从 1 开始）
# 要求：用差分建"每天借出量"（d[L]+=v; d[R+1]-=v），前缀和复原；
#       **每处理完一个申请就检验一次**，发现不行立刻输出并结束
# 提示：想清楚"为什么不能把所有申请一起差分完再检验"（答案在练习题里）
# 自测：所有申请刚好卡在上限（能过）、第 1 个就不行、最后一个才不行、
#       多申请叠在同一天、有位置超量但不是第一个超的（考验"编号最小"）

# ===== 你的代码写在这里 =====
n=int(input())
r=[0]+list(map(int,input().split()))
k=int(input())
d=[0]*(n+2)
for i in range(k):
    L,R,v=map(int,input().split())
    d[L]+=v
    d[R+1]-=v
    cur=0
    for j in range(1,n+1):
        cur+=d[j]
        if cur>r[j]:
            print(i+1)
            print(j)
            exit(0)
print(0)



