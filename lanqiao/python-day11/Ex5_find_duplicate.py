# 题 5：找重复数字（快慢指针 / Floyd 判圈）⭐⭐⭐
# 输入：第一行 n；第二行 n+1 个整数（每个都在 [1, n] 之间）
# 输出：一行一个整数 —— 那个重复的数字
# 保证：恰好有一个数字出现了多次，其余数字都恰好出现 1 次
# 数据：1 <= n <= 100000
# 要求：快慢指针（Floyd 判圈），O(n) 时间、额外空间 O(1)；
#       不许排序、不许开计数数组、不许用 set（这题的全部意义就是 O(1) 空间）
# 提示：把下标当节点、把 a[i] 当成 i 的 next 指针 → 这串数必然带环，环的入口就是重复的数字
#       三步：① slow = a[0], fast = a[a[0]]，追到相遇
#             ② p = 0
#             ③ p 和 slow 同速前进，相遇处就是答案
#       ⚠️ 第一步的起点不能是 0 和 0（那样第一轮就"相遇"了）
# 自测：n = 1、重复的数字在第一位、在最后一位、a[0] 自己就是重复的、同一数字出现 3 次

# ===== 你的代码写在这里 =====
n=int(input())
a=list(map(int,input().split()))
slow=a[0]
fast=a[a[0]]
while slow!=fast:
    slow=a[slow]
    fast=a[a[fast]]
p=0
while p!=slow:
    p=a[p]
    slow=a[slow]
print(p)

